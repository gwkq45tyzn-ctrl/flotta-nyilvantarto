import assert from 'node:assert/strict';
import {parseDay,parseTime} from './import-dates.mjs';
assert.equal(parseDay('2026-10-30'),'2026-10-30');
assert.equal(parseDay('2026-10-30 06:35:09'),'2026-10-30');
assert.equal(parseDay('30.10.2026'),'2026-10-30');
assert.equal(parseDay('30/10/2026'),'2026-10-30');
assert.equal(parseDay('10/30/2026'),'2026-10-30');
assert.equal(parseDay('05/10/2026'),'2026-10-05');
assert.equal(parseDay('05/10/2026','MDY'),'2026-05-10');
assert.equal(parseDay('31.02.2026'),'');
assert.equal(parseDay('2026-02-29'),'');
assert.equal(parseDay('2024-02-29'),'2024-02-29');
assert.equal(parseDay('bad-date'),'');
assert.equal(parseDay(46325),'2026-10-30');
assert.equal(parseTime('10/30/2026 6:05:04').eventTime,'2026-10-30T06:05:04');
assert.equal(parseTime('30.10.2026 06:05:04').eventTime,'2026-10-30T06:05:04');
assert.equal(parseTime('10/30/2026 6:05 PM').eventTime,'2026-10-30T18:05:00');
assert.equal(parseTime('10/30/2026 12:00 AM').eventTime,'2026-10-30T00:00:00');
assert.equal(parseTime('10/30/2026 12:00 PM').eventTime,'2026-10-30T12:00:00');
assert.equal(parseTime('10/30/2026 25:05').date,'');
assert.equal(parseTime('bad').date,'');
assert.equal(parseTime('10/30/2026').timeKnown,false);
assert.equal(parseTime(46325.25).eventTime,'2026-10-30T06:00:00');
console.log('PASS: locale-safe Hungarian / US / ISO / Excel dates and timestamps');
