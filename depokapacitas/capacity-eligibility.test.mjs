import assert from 'node:assert/strict';
import {assessBooking,effectiveCapacity,eligibleDriver,eligibleVehicle} from './capacity-eligibility.mjs';
const today='2026-10-30';
const drivers=[{id:'D1',active:true},{id:'D2',active:false},{id:'D3'}];
const vehicles=[{id:'CAR1',status:'Elérhető'},{id:'CAR2',status:'Szerviz'},{id:'CAR3',status:'Leállított'}];
const base={date:today,driverId:'D1',vehicleId:'CAR1',capacity:105};
assert.equal(effectiveCapacity(base,drivers,vehicles,today),105);
assert.equal(effectiveCapacity({...base,vehicleId:'CAR2'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,vehicleId:'CAR3'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,driverId:'D2'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,driverId:'D3'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,driverId:'UNKNOWN'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,vehicleId:'UNKNOWN'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,date:'2026-10-31',vehicleId:'CAR2'},drivers,vehicles,today),0);
assert.equal(effectiveCapacity({...base,date:'2026-10-29',vehicleId:'CAR2'},drivers,vehicles,today),105);
assert.equal(assessBooking({...base,vehicleId:'CAR2'},drivers,vehicles,today).reason,'vehicle_unavailable');
assert.equal(assessBooking({...base,driverId:'D2'},drivers,vehicles,today).reason,'driver_inactive');
assert.equal(eligibleDriver(drivers[0]),true);
assert.equal(eligibleDriver(drivers[2]),false);
assert.equal(eligibleVehicle(vehicles[0]),true);
assert.equal(eligibleVehicle(vehicles[1]),false);
assert.equal(effectiveCapacity({...base,capacity:-9},drivers,vehicles,today),0);
console.log('PASS: safe capacity planning for 16 cases');
