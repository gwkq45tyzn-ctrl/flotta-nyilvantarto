import assert from 'node:assert/strict';
import {planSharedMasterMigration} from './shared-import-plan.mjs';
const sample={drivers:[{id:'old1',daCode:'D2104608',name:'Minta Futár',agency:'Szövetkezet',status:'aktiv'}],vehicles:[{id:'old2',rendszam:'AAA-123',gyartmany:'Ford',modell:'Transit',status:'szerviz'}]};
let p=planSharedMasterMigration(sample);
assert.equal(p.counts.newDrivers,1);
assert.equal(p.counts.newVehicles,1);
assert.equal(p.counts.blockers,0);
assert.equal(p.proposed.vehicles.create[0].data.status,'Szerviz');
assert.deepEqual(Object.keys(p.proposed.drivers.create[0].data).sort(),['active','capacity','daCode','name','vendor'].sort());
assert.equal(p.importEnabled,false);
p=planSharedMasterMigration(sample,{drivers:[{id:'D2104608',name:'Minta Futár',daCode:'D2104608',vendor:'Szövetkezet',active:true,capacity:110}],vehicles:[{id:'AAA123',plate:'AAA123',model:'Ford Transit',status:'Szerviz'}]});
assert.equal(p.counts.newDrivers,0);
assert.equal(p.counts.matchedDrivers,1);
assert.equal(p.counts.matchedVehicles,1);
assert.equal(p.counts.blockers,0);
p=planSharedMasterMigration(sample,{drivers:[{id:'D2104608',name:'Másik Futár',daCode:'D2104608',vendor:'Szövetkezet',active:true}],vehicles:[]});
assert.equal(p.counts.conflictingDrivers,1);
assert.equal(p.readyForReview,false);
p=planSharedMasterMigration(sample,{drivers:[],vehicles:[{id:'AAA-123',plate:'AAA-123',model:'Ford Transit',status:'Szerviz'},{id:'AAA123',plate:'AAA123',model:'Ford Transit',status:'Szerviz'}]});
assert.ok(p.problems.some(x=>x.type==='duplicate_existing'));
p=planSharedMasterMigration({drivers:[{...sample.drivers[0],daCode:''}],vehicles:sample.vehicles});
assert.ok(p.counts.blockers>0);
assert.equal(p.importEnabled,false);
console.log('PASS: staging-only master data plan, conflict checks, no writes');
