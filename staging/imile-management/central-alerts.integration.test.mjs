import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const depot=read('../../depokapacitas/app.js');
const html=read('../../depokapacitas/index.html');
const build=read('./build-preview.mjs');
const aggregator=read('./central-alerts.mjs');
assert.match(depot,/import \{collectFleetAlerts\} from '\.\.\/staging\/imile-management\/central-alerts\.mjs'/);
assert.match(depot,/const state=.*fleetRecords:\[\],fleetAssignments:\[\]/);
assert.match(depot,/for\(const name of \[[^\]]*'fleetRecords','fleetAssignments'/);
assert.match(depot,/return datebar\(\)\+centralTaskList\(8\)/);
assert.match(depot,/return datebar\(\)\+centralTaskList\(5\)/);
assert.match(depot,/function alertsView\(\)\{return datebar\(\)\+centralTaskList\(null\);\}/);
assert.match(depot,/const c=\{overview,alerts:alertsView/);
assert.match(html,/data-view="alerts"/);
assert.match(build,/'staging\/imile-management\/central-alerts\.mjs'/);
assert.match(aggregator,/import \{expiryWarnings, schemas, validDate\}/);
assert.doesNotMatch(aggregator,/\b(?:setDoc|updateDoc|deleteDoc|writeBatch|runTransaction|UrlFetchApp|SpreadsheetApp)\s*\(/);
console.log('PASS: unified Fleet alerts use shared staging Firestore reads in both Depot views and preview bundle');
