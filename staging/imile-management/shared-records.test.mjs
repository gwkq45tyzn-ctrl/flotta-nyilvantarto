import assert from 'node:assert/strict';
import {previewFleetMigration,canonicalDa,canonicalPlate,normalizeVehicleStatus} from './shared-records.mjs';
assert.equal(canonicalDa(' d210 4608 '),'D2104608');
assert.equal(canonicalPlate(' ABC - 123 '),'ABC123');
assert.equal(normalizeVehicleStatus('szerviz'),'Szerviz');
assert.equal(normalizeVehicleStatus('hasznalatban'),'Elérhető');
let p=previewFleetMigration({vehicles:[{id:'v1',rendszam:'ABC-123',status:'szerviz',gyartmany:'Ford',modell:'Transit'}],drivers:[{id:'d1',name:'Minta futár',daCode:' D210123456 ',agency:'Minta vállalkozó',status:'aktiv'}]});
assert.equal(p.counts.critical,0);
assert.equal(p.vehicles[0].status,'Szerviz');
assert.equal(p.vehicles[0].id,'ABC123');
assert.equal(p.drivers[0].id,'D210123456');
assert.equal(p.drivers[0].capacity,0);
assert.equal(p.uploadEnabled,false);
p=previewFleetMigration({vehicles:[{id:'a',rendszam:'ABC-123',status:'aktiv'},{id:'b',rendszam:'ABC123',status:'aktiv'}],drivers:[{id:'x',name:'Futár',daCode:'',status:'aktiv'}]});
assert.ok(p.counts.critical>=2);
assert.ok(p.issues.some(x=>x.type==='duplicate'&&x.target==='vehicle'));
assert.ok(p.issues.some(x=>x.type==='missing_or_invalid_da'));
assert.equal(p.readyForManualReview,false);
assert.throws(()=>previewFleetMigration({vehicles:[]}),/drivers/);
assert.throws(()=>previewFleetMigration(null),/JSON objektum/);
console.log('STAGING: közös törzsadat-migrációs ellenőrzések rendben.');
